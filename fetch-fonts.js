const https = require('https');
const fs = require('fs');
const path = require('path');

const OUT = __dirname;
fs.mkdirSync(OUT, { recursive: true });

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

const FAMILIES = [
  { css: 'family=Cormorant+Garamond:ital,wght@0,300;0,400;0,500;0,600;1,300;1,400', slug: 'cormorant' },
  { css: 'family=Jost:wght@300;400;500', slug: 'jost' },
  { css: 'family=Tajawal:wght@300;400;500;700', slug: 'tajawal' }
];

const WANT = new Set(['latin', 'latin-ext', 'arabic']);

function get(url, headers) {
  return new Promise((res, rej) => {
    https.get(url, { headers }, (r) => {
      if (r.statusCode >= 300 && r.statusCode < 400 && r.headers.location) return get(r.headers.location, headers).then(res, rej);
      const chunks = [];
      r.on('data', c => chunks.push(c));
      r.on('end', () => res({ status: r.statusCode, body: Buffer.concat(chunks).toString('utf8') }));
    }).on('error', rej);
  });
}

function getBin(url) {
  return new Promise((res, rej) => {
    https.get(url, { headers: { 'user-agent': UA } }, (r) => {
      if (r.statusCode >= 300 && r.statusCode < 400 && r.headers.location) return getBin(r.headers.location).then(res, rej);
      const chunks = [];
      r.on('data', c => chunks.push(c));
      r.on('end', () => res(Buffer.concat(chunks)));
    }).on('error', rej);
  });
}

// Google's css2 output is: /* subset */ @font-face { ... }
const RE = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;

(async () => {
  let out = '/* Self-hosted webfonts for GLADIA Cafe demo. Generated by fetch-fonts.js - do not edit by hand. */\n';
  const seen = new Set();
  for (const f of FAMILIES) {
    const url = `https://fonts.googleapis.com/css2?${f.css}&display=swap`;
    const { status, body } = await get(url, { 'user-agent': UA });
    if (status !== 200) { console.log('CSS FAIL', f.slug, status); continue; }
    RE.lastIndex = 0;
    let m;
    while ((m = RE.exec(body)) !== null) {
      const subset = m[1];
      if (!WANT.has(subset)) continue;
      const block = m[2];
      const urlM = block.match(/url\((https:\/\/[^)]+\.woff2)\)/);
      const weightM = block.match(/font-weight:\s*([0-9]+)/);
      const styleM = block.match(/font-style:\s*(\w+)/);
      const rangeM = block.match(/unicode-range:\s*([^;}]+)/);
      const familyM = block.match(/font-family:\s*'([^']+)'/);
      if (!urlM || !familyM) continue;
      const weight = weightM ? weightM[1] : '400';
      const style = styleM ? styleM[1] : 'normal';
      const fname = `${f.slug}-${weight}${style === 'italic' ? 'i' : ''}-${subset}.woff2`;
      if (!seen.has(fname)) {
        const buf = await getBin(urlM[1]);
        fs.writeFileSync(path.join(OUT, fname), buf);
        seen.add(fname);
      }
      out += `@font-face{font-family:'${familyM[1]}';font-style:${style};font-weight:${weight};font-display:swap;src:url('${fname}') format('woff2');unicode-range:${rangeM ? rangeM[1].trim() : 'U+0000-00FF'};}\n`;
    }
  }
  fs.writeFileSync(path.join(__dirname, 'fonts.css'), out);
  console.log('fonts done:', seen.size, 'files');
})();
